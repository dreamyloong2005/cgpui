// Shaders are written in Slang (src/renderer/shaders, vulkan/shaders,
// metal/shaders); scripts/dev/compile_shaders.py compiles them into the
// checked-in SPIR-V (src/renderer/vulkan/generated) and Metal sources
// (src/renderer/metal/generated). Each output names its Slang sources with an
// FNV-1a 64 hash of their text (LF line ends): an edited shader that was not
// compiled again fails here. No GLSL remains, and the renderer asks for the
// Vulkan version its SPIR-V needs.
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <iterator>
#include <set>
#include <sstream>
#include <string>
#include <string_view>

namespace {

const std::filesystem::path root{CGPUI_SOURCE_ROOT};

std::string read_source(std::string_view path) {
  std::ifstream source(root / std::filesystem::path{path}, std::ios::binary);
  return source ? std::string{std::istreambuf_iterator<char>(source), {}}
                : std::string{};
}

bool has(const std::string& text, std::string_view value) {
  return text.find(value) != std::string::npos;
}

std::string fnv1a64(const std::string& text) {
  std::uint64_t value = 0xCBF29CE484222325ULL;
  for (std::size_t i = 0; i < text.size(); ++i) {
    if (text[i] == '\r' && i + 1 < text.size() && text[i + 1] == '\n') {
      continue;
    }
    value = (value ^ static_cast<unsigned char>(text[i])) * 0x100000001B3ULL;
  }
  std::ostringstream out;
  out.width(16);
  out.fill('0');
  out << std::hex << value;
  return out.str();
}

int fail(int code, const std::string& message) {
  std::cerr << "shader source structure: " << message << '\n';
  return code;
}

}  // namespace

int main() {
  constexpr std::string_view outputs[] = {
      "src/renderer/dx12/generated/rounded_rect_dxil.inc",
      "src/renderer/dx12/generated/text_dxil.inc",
      "src/renderer/dx12/generated/image_dxil.inc",
      "src/renderer/dx12/generated/box_shadow_dxil.inc",
      "src/renderer/vulkan/generated/rounded_rect_spirv.inc",
      "src/renderer/vulkan/generated/text_spirv.inc",
      "src/renderer/vulkan/generated/image_spirv.inc",
      "src/renderer/vulkan/generated/box_shadow_spirv.inc",
      "src/renderer/vulkan/generated/backdrop_blur_spirv.inc",
      "src/renderer/metal/generated/cgpui_vertex.metal",
      "src/renderer/metal/generated/cgpui_solid_fragment.metal",
      "src/renderer/metal/generated/cgpui_rounded_fragment.metal",
      "src/renderer/metal/generated/cgpui_glyph_fragment.metal",
      "src/renderer/metal/generated/cgpui_image_fragment.metal",
      "src/renderer/metal/generated/cgpui_box_shadow_vertex.metal",
      "src/renderer/metal/generated/cgpui_box_shadow_fragment.metal",
      "src/renderer/metal/generated/cgpui_backdrop_fragment.metal",
  };
  std::set<std::string> named;
  for (const std::string_view output : outputs) {
    const std::string text = read_source(output);
    const auto generator = output.starts_with("src/renderer/dx12/")
        ? "// Generated by scripts/dev/compile_dx12_shaders.py"
        : "// Generated by scripts/dev/compile_shaders.py";
    if (!has(text, generator)) {
      return fail(1, std::string{output} + " is not a compile_shaders.py output");
    }
    std::istringstream lines{text};
    for (std::string line; std::getline(lines, line);) {
      constexpr std::string_view prefix = "// source ";
      if (line.rfind(prefix, 0) != 0) continue;
      std::istringstream fields{line.substr(prefix.size())};
      std::string path, label, hash;
      fields >> path >> label >> hash;
      named.insert(path);
      const std::string source = read_source(path);
      if (source.empty() || label != "fnv1a64" || fnv1a64(source) != hash) {
        return fail(2, path + " changed since " + std::string{output} +
                           " was generated: run scripts/dev/compile_shaders.py");
      }
    }
  }
  for (const char* directory : {"src/renderer/shaders", "src/renderer/vulkan/shaders",
                                "src/renderer/metal/shaders"}) {
    for (const auto& entry : std::filesystem::directory_iterator(root / directory)) {
      const std::string path = std::string{directory} + "/" +
                               entry.path().filename().generic_string();
      if (entry.path().extension() != ".slang" || !named.contains(path)) {
        return fail(3, path + " is not a Slang source of a generated output");
      }
    }
  }
  for (const auto& entry : std::filesystem::recursive_directory_iterator(root / "src")) {
    const std::string extension = entry.path().extension().string();
    if (extension == ".glsl" || extension == ".vert" || extension == ".frag" ||
        (extension == ".metal" &&
         entry.path().parent_path().filename() != "generated")) {
      return fail(4, entry.path().generic_string() + ": shaders are written in Slang");
    }
  }
  const std::string script = read_source("scripts/dev/compile_shaders.py");
  const std::string instance =
      read_source("src/renderer/vulkan/vulkan_instance_surface.cpp");
  const std::string device =
      read_source("src/renderer/vulkan/vulkan_physical_device.cpp");
  if (!has(script, "\"spirv_1_3\"") || !has(script, "\"vulkan1.1\"") ||
      !has(instance, ".apiVersion = VK_API_VERSION_1_1") ||
      !has(instance, "vkEnumerateInstanceVersion") ||
      !has(device, "properties.apiVersion < VK_API_VERSION_1_1")) {
    return fail(5, "SPIR-V 1.3 needs the Vulkan 1.1 instance and devices");
  }
  const std::string metal_build = read_source("packages/renderer-metal/build.mcpp");
  const std::string metal_library =
      read_source("src/renderer/metal/metal_pipeline_library.mm");
  if (!has(metal_build, "src/renderer/metal/generated") ||
      !has(metal_library, "kCgpuiMetalShaders")) {
    return fail(6, "the Metal renderer embeds the generated sources");
  }
  const std::string dx12_script = read_source("scripts/dev/compile_dx12_shaders.py");
  const std::string dx12_library = read_source("src/renderer/dx12/dx12_shader_binaries.cpp");
  if (!has(script, "--dxil") || !has(dx12_script, "sm_6_0") ||
      !has(dx12_script, "CGPUI_CLIP_Y_UP") || !has(dx12_script, "-dumpbin") ||
      !has(dx12_library, "generated/rounded_rect_dxil.inc") ||
      !has(dx12_library, "generated/text_dxil.inc") ||
      !has(dx12_library, "generated/image_dxil.inc") ||
      !has(dx12_library, "generated/box_shadow_dxil.inc")) {
    return fail(7, "DX12 must validate and embed shaders from the shared Slang source");
  }
  return 0;
}
