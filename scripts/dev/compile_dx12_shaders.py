#!/usr/bin/env python3
"""Compile the existing rectangle Slang shader to embedded DXIL (no runtime compiler)."""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import compile_shaders as shared

SOURCE = "src/renderer/vulkan/shaders/rounded_rect.slang"
OUTPUT = "src/renderer/dx12/generated/rounded_rect_dxil.inc"
FLAGS = ["-target", "dxil", "-profile", "sm_6_0", "-O2", "-DCGPUI_CLIP_Y_UP=1"]


def output() -> str:
    compiler = shared.tool("SLANGC", "slangc")
    validator = shared.tool("DXC", "dxc")
    body = []
    with tempfile.TemporaryDirectory() as directory:
        for entry, stage in (("vertex_main", "vertex"), ("fragment_main", "fragment")):
            output = Path(directory) / f"{entry}.dxil"
            shared.compile_one(compiler, SOURCE, entry, stage, FLAGS, output)
            data = output.read_bytes()
            if data[:4] != b"DXBC":
                raise SystemExit("Slang did not emit a DXIL container")
            shared.run([validator, "-dumpbin", str(output)])
            name = "rect_vertex_dxil" if stage == "vertex" else "rect_fragment_dxil"
            body.append(f"constexpr std::array<std::uint8_t, {len(data)}> {name}{{")
            for index in range(0, len(data), 16):
                body.append("    " + " ".join(f"0x{x:02x}," for x in data[index:index + 16]))
            body.append("};")
    lines = shared.header(body, shared.slangc_version(compiler), FLAGS, shared.sources(SOURCE))
    lines[0] = "// Generated by scripts/dev/compile_dx12_shaders.py; do not edit."
    return "\n".join(lines) + "\n"


def main() -> int:
    content = output()
    target = shared.REPO / OUTPUT
    if target.exists() and target.read_text("utf-8") == content:
        return 0
    if "--check" in sys.argv[1:]:
        print("stale: " + OUTPUT)
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, "utf-8", newline="\n")
    print("wrote: " + OUTPUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
