#!/usr/bin/env python3
"""Shared steps of the CGPUI SDK packages (docs/sdk-packaging.md).

check-clean  refuses a checkout with tracked changes (and, unless
             --allow-untracked, untracked files that are not ignored).
workspace    writes a packaging workspace: the root mcpp.toml's library and
             example members, read from another directory, with the C++
             runtime the package needs (the CRT is one setting per graph).
finalize     turns a windows-package.ps1 / linux-package.sh package into an
             SDK: bundled vendored static libraries, link order from the
             example_workbench dependency graph, system libraries from its
             mcpp link line, manifest.json with toolchain, mcpp version,
             vendored dependency versions and a SHA-256 for every file, a
             CMake config package, the consumer sample and README.md.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tomllib
from pathlib import Path

LINUX_SYSTEM_PACKAGES = (
    "harfbuzz", "freetype2", "fontconfig", "wayland", "libxkbcommon",
    "dbus", "vulkan-icd-loader", "libxml2",
)
LINK_ROOT = "examples/workbench"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True,
        text=True).stdout


def status_lines(repo: Path) -> list[str]:
    output = git(repo, "status", "--porcelain", "--untracked-files=all")
    return [line for line in output.splitlines() if line.strip()]


def check_clean(repo: Path, allow_untracked: bool) -> None:
    problems = []
    for line in status_lines(repo):
        path = line[3:].strip('"')
        if line.startswith("??"):
            if not allow_untracked:
                problems.append(f"untracked: {path}")
        else:
            problems.append(f"changed: {path}")
    if problems:
        raise SystemExit(
            f"refusing to package {repo}: the tree is not clean\n  "
            + "\n  ".join(problems))


def write_workspace(repo: Path, output: Path, cxx_runtime: str) -> None:
    """A workspace in `output` over the repository's library and example
    members (not tests or tools), with `cxx_runtime` for the whole graph."""
    text = (repo / "mcpp.toml").read_text("utf-8")
    members = tomllib.loads(text)["workspace"]["members"]
    relative = Path(os.path.relpath(repo, output)).as_posix()
    chosen = [m for m in members if not m.startswith("tests/")]
    listing = "".join(f'    "{relative}/{m}",\n' for m in chosen)
    text = re.sub(r"members = \[\n.*?\n\]", "members = [\n" + listing + "]",
                  text, count=1, flags=re.S)
    text, count = re.subn(r'cxx_runtime = "[a-z-]+"',
                          f'cxx_runtime = "{cxx_runtime}"', text)
    if count != 1:
        raise SystemExit("mcpp.toml: expected one [workspace.build] cxx_runtime")
    header = ("# Generated by scripts/ci/sdk-package.py workspace from the "
              "repository's mcpp.toml; do not edit.\n")
    write_text(output / "mcpp.toml", header + text)
    print(output / "mcpp.toml")


def cfg_matches(selector: str, platform: str) -> bool:
    """Evaluates the cfg(...) selectors the manifests use, for an OS."""
    expression = selector.strip()
    match = re.fullmatch(r"cfg\((.*)\)", expression)
    if match:
        expression = match.group(1)

    def evaluate(text: str) -> bool:
        text = text.strip()
        inner = re.fullmatch(r"(not|any|all)\((.*)\)", text)
        if inner:
            parts = [p for p in re.split(r",\s*(?![^()]*\))", inner.group(2)) if p.strip()]
            values = [evaluate(part) for part in parts]
            return {"not": lambda: not values[0], "any": lambda: any(values),
                    "all": lambda: all(values)}[inner.group(1)]()
        os_match = re.fullmatch(r'os\s*=\s*"([a-z]+)"', text)
        if not os_match:
            raise SystemExit(f"unsupported cfg selector: {selector}")
        return os_match.group(1) == platform

    return evaluate(expression)


def package_dependencies(package: Path, platform: str) -> list[Path]:
    manifest = tomllib.loads((package / "mcpp.toml").read_text("utf-8"))
    tables = [manifest.get("dependencies", {})]
    for selector, table in manifest.get("target", {}).items():
        if cfg_matches(selector, platform):
            tables.append(table.get("dependencies", {}))
    result = []
    for table in tables:
        for namespace in table.values():
            for entry in namespace.values():
                result.append((package / entry["path"]).resolve())
    return result


def link_order(repo: Path, platform: str) -> list[dict]:
    """The libraries of example_workbench's dependency graph, each before
    the libraries it depends on (reverse post-order of a depth-first walk
    in manifest order): the order a single-pass linker needs."""
    order: list[Path] = []
    seen: set[Path] = set()

    def visit(package: Path) -> None:
        if package in seen:
            return
        seen.add(package)
        for dependency in package_dependencies(package, platform):
            visit(dependency)
        order.append(package)

    visit((repo / LINK_ROOT).resolve())
    libraries = []
    for package in reversed(order[:-1]):
        manifest = tomllib.loads((package / "mcpp.toml").read_text("utf-8"))
        targets = [name for name, target in manifest.get("targets", {}).items()
                   if target.get("kind") == "lib"]
        if len(targets) != 1:
            raise SystemExit(f"{package}: expected one lib target, found {targets}")
        info = manifest["package"]
        vendored = package.parent.name == "third_party"
        libraries.append({
            "name": targets[0], "package": info["name"],
            "origin": f"vendored {info['name']} {info['version']}" if vendored else "cgpui",
        })
    return libraries


def link_edge(build_dir: Path, program: str) -> list[str]:
    """The ldflags words of a program's link edge in mcpp's build.ninja."""
    lines = (build_dir / "build.ninja").read_text("utf-8").splitlines()
    pattern = re.compile(rf"^build \S*/{re.escape(program)}(\.exe)? :")
    for index, line in enumerate(lines):
        if pattern.match(line):
            for following in lines[index + 1:index + 12]:
                stripped = following.strip()
                if stripped.startswith("ldflags ="):
                    return re.findall(r'"[^"]*"|\S+', stripped[len("ldflags ="):])
                if following.startswith("build "):
                    break
            return []
    raise SystemExit(f"no {program} link edge in {build_dir / 'build.ninja'}")


def system_libraries(words: list[str], platform: str, own: set[str]) -> tuple[list[str], list[str]]:
    names, dirs = [], []
    for word in words:
        word = word.strip('"')
        if platform == "windows":
            if word.upper().startswith("/LIBPATH:"):
                dirs.append(word[len("/LIBPATH:"):])
            elif word.lower().endswith(".lib"):
                names.append(word[:-4])
        elif word.startswith("-L"):
            dirs.append(word[2:])
        elif word.startswith("-l"):
            names.append(word[2:])
    ordered = [name for name in dict.fromkeys(names) if name not in own]
    return ordered, dirs


def run_text(command: list[str]) -> str:
    result = subprocess.run(command, capture_output=True, text=True,
                            errors="replace")
    return (result.stdout + result.stderr).strip()


def compiler_path(build_dir: Path) -> str:
    entries = json.loads((build_dir / "compile_commands.json").read_text("utf-8"))
    for entry in entries:
        words = entry.get("arguments") or entry["command"].split()
        if words and Path(words[0]).name.lower() in ("cl.exe", "g++", "c++", "clang++"):
            return words[0]
    raise SystemExit(f"no C++ compiler in {build_dir / 'compile_commands.json'}")


def compiler_info(build_dir: Path, platform: str) -> dict:
    compiler = compiler_path(build_dir)
    if platform == "windows":
        # The banner may be localized; the version follows "C/C++".
        banner = next((line for line in run_text([compiler]).splitlines()
                       if "C/C++" in line), "unknown")
        version = re.search(r"C/C\+\+\D*(\d+\.\d+\.\d+)", banner)
        return {"id": "msvc", "path": compiler,
                "version": version.group(1) if version else "unknown",
                "toolset": Path(compiler).parents[3].name}
    banner = run_text([compiler, "--version"]).splitlines()[0]
    version = re.search(r"(\d+\.\d+\.\d+)", banner)
    return {"id": "gcc" if "GCC" in banner or "g++" in banner else "clang",
            "path": compiler, "banner": banner,
            "version": version.group(1) if version else "unknown"}


def msvc_runtime(build_dir: Path, library: Path) -> str:
    """The CRT a static library was compiled for, from its directives."""
    link = str(Path(compiler_path(build_dir)).with_name("link.exe"))
    directives = run_text([link, "/dump", "/directives", str(library)]).upper()
    debug = "MSVCRTD" in directives or "LIBCMTD" in directives
    if "MSVCRT" in directives:
        return "MDd" if debug else "MD"
    if "LIBCMT" in directives:
        return "MTd" if debug else "MT"
    return "unknown"


def vulkan_sdk_version(dirs: list[str]) -> str | None:
    for directory in dirs:
        match = re.search(r"VulkanSDK[\/]+([\d.]+)", directory)
        if match:
            return match.group(1)
    return None


def pacman_versions() -> dict[str, str]:
    versions = {}
    for package in LINUX_SYSTEM_PACKAGES:
        output = run_text(["pacman", "-Q", package]).split()
        versions[package] = output[1] if len(output) == 2 else "not installed"
    return versions


def tree_sha256(repo: Path, directory: str) -> str:
    """SHA-256 over the committed files of a directory (the bytes in HEAD,
    so line-ending conversion of a checkout does not change it): one line
    `<sha256>  <path>` per file, sorted by path (sha256sum format)."""
    files = sorted(n for n in git(repo, "ls-tree", "-r", "-z", "--name-only",
                                  "HEAD", "--", directory).split("\0") if n)
    lines = []
    for name in files:
        blob = subprocess.run(["git", "-C", str(repo), "show", f"HEAD:{name}"],
                              check=True, capture_output=True).stdout
        lines.append(f"{hashlib.sha256(blob).hexdigest()}  {name}\n")
    return hashlib.sha256("".join(lines).encode("utf-8")).hexdigest()


def vendored_dependencies(repo: Path, bundled: set[str]) -> list[dict]:
    """third_party/VENDORED.md rows, with a SHA-256 of each committed tree."""
    rows = []
    table = (repo / "third_party" / "VENDORED.md").read_text("utf-8")
    for line in table.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 6 or not cells[0].startswith("`") or cells[0] == "Directory":
            continue
        directory = cells[0].strip("`").rstrip("/")
        name = re.sub(r"\[([^\]]+)\].*", r"\1", cells[1])
        rows.append({
            "name": name,
            "directory": f"third_party/{directory}",
            "version": cells[2].strip("`"),
            "upstream_commit": cells[3].strip("`"),
            "license": cells[4],
            "source_archive_sha256": cells[5].strip("`") if cells[5] != "-" else None,
            "tree_sha256": tree_sha256(repo, f"third_party/{directory}"),
            "bundled": directory in bundled,
        })
    return rows


def mcpp_info(mcpp: str, workspace: Path) -> dict:
    version = run_text([mcpp, "--version"]).splitlines()[0]
    manifest = tomllib.loads((workspace / "mcpp.toml").read_text("utf-8"))
    return {"version": version.removeprefix("mcpp ").strip(), "path": mcpp,
            "toolchain": manifest["workspace"].get("toolchain", {}),
            "cxx_runtime": manifest["workspace"]["build"]["cxx_runtime"]}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_entries(package_root: Path) -> list[dict]:
    files = sorted(
        (path.relative_to(package_root).as_posix(), path)
        for path in package_root.rglob("*")
        if path.is_file() and path.name not in (
            "manifest.json", "release-manifest.json"))
    return [{"path": relative, "size": path.stat().st_size,
             "sha256": sha256(path)} for relative, path in files]


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def project_version(repo: Path) -> str:
    manifest = tomllib.loads((repo / "packages/core/mcpp.toml").read_text("utf-8"))
    return manifest["package"]["version"]


def cmake_config(platform: str, mode: str, runtime: str | None,
                 libraries: list[dict], system: list[str]) -> str:
    """cgpuiConfig.cmake: one imported static target per library and
    cgpui::cgpui linking all of them in link order, then the system
    libraries."""
    lines = [
        "# Generated by scripts/ci/sdk-package.py; see docs/sdk-packaging.md.",
        "cmake_minimum_required(VERSION 3.21)",
        "include(CMakeFindDependencyMacro)",
        'get_filename_component(_cgpui_prefix "${CMAKE_CURRENT_LIST_DIR}/../../.." ABSOLUTE)',
        f'set(cgpui_PLATFORM "{platform}")',
        f'set(cgpui_BUILD_MODE "{mode}")',
    ]
    if platform == "windows":
        lines += [
            f'set(cgpui_MSVC_RUNTIME "{runtime}")',
            # mcpp has no debug CRT: both packages use the release DLL CRT
            # (/MD), so a consumer's Debug configuration must use it too.
            "if(NOT DEFINED CMAKE_MSVC_RUNTIME_LIBRARY)",
            '  set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreadedDLL")',
            'elseif(NOT CMAKE_MSVC_RUNTIME_LIBRARY STREQUAL "MultiThreadedDLL")',
            '  message(FATAL_ERROR "cgpui was built with /${cgpui_MSVC_RUNTIME}; '
            'set CMAKE_MSVC_RUNTIME_LIBRARY to MultiThreadedDLL '
            '(it is ${CMAKE_MSVC_RUNTIME_LIBRARY})")',
            "endif()",
            "find_dependency(Vulkan)",
        ]
    lines += ["if(NOT TARGET cgpui::cgpui)"]
    link_items = []
    for library in libraries:
        target = f"cgpui::{library['name']}"
        lines += [
            f"  add_library({target} STATIC IMPORTED)",
            f"  set_target_properties({target} PROPERTIES",
            f'    IMPORTED_LOCATION "${{_cgpui_prefix}}/{library["path"]}")',
        ]
        link_items.append(target)
    for name in system:
        vulkan = name in ("vulkan-1",) and platform == "windows"
        link_items.append("Vulkan::Vulkan" if vulkan else name)
    lines += [
        "  add_library(cgpui::cgpui INTERFACE IMPORTED)",
        "  set_target_properties(cgpui::cgpui PROPERTIES",
        '    INTERFACE_INCLUDE_DIRECTORIES "${_cgpui_prefix}/include"',
        "    INTERFACE_COMPILE_FEATURES cxx_std_23",
        '    INTERFACE_LINK_LIBRARIES "' + ";".join(link_items) + '")',
        "endif()",
        "unset(_cgpui_prefix)",
        "",
    ]
    return "\n".join(lines)


def cmake_version_file(version: str) -> str:
    """Compatible when the request is not newer and the major version
    matches (0.x: the minor version too)."""
    return "\n".join([
        "# Generated by scripts/ci/sdk-package.py.",
        f'set(PACKAGE_VERSION "{version}")',
        'string(REPLACE "." ";" _cgpui_have "${PACKAGE_VERSION}")',
        'string(REPLACE "." ";" _cgpui_want "${PACKAGE_FIND_VERSION}.0.0")',
        "list(GET _cgpui_have 0 _cgpui_have_major)",
        "list(GET _cgpui_have 1 _cgpui_have_minor)",
        "list(GET _cgpui_want 0 _cgpui_want_major)",
        "list(GET _cgpui_want 1 _cgpui_want_minor)",
        "set(PACKAGE_VERSION_COMPATIBLE FALSE)",
        "if(NOT PACKAGE_FIND_VERSION OR",
        "   (PACKAGE_FIND_VERSION VERSION_LESS_EQUAL PACKAGE_VERSION AND",
        "    _cgpui_have_major EQUAL _cgpui_want_major AND",
        "    (NOT _cgpui_have_major EQUAL 0 OR",
        "     _cgpui_have_minor EQUAL _cgpui_want_minor)))",
        "  set(PACKAGE_VERSION_COMPATIBLE TRUE)",
        "endif()",
        "if(PACKAGE_FIND_VERSION VERSION_EQUAL PACKAGE_VERSION)",
        "  set(PACKAGE_VERSION_EXACT TRUE)",
        "endif()",
        'if(NOT CMAKE_SIZEOF_VOID_P EQUAL 8)',
        '  set(PACKAGE_VERSION "${PACKAGE_VERSION} (64-bit)")',
        "  set(PACKAGE_VERSION_UNSUITABLE TRUE)",
        "endif()",
        "",
    ])


