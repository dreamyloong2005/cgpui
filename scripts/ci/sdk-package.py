#!/usr/bin/env python3
"""Shared steps of the CGPUI SDK packages (docs/sdk-packaging.md).

check-clean  refuses a checkout with tracked changes (and, unless
             --allow-untracked, untracked files that are not ignored).
workspace    writes a packaging workspace: the root mcpp.toml's library and
             example members, read from another directory, with the C++
             runtime the package needs (the CRT is one setting per graph).
stage-macos  adds the link and header closure, CMake config, sample and
             manifest to a native Phase J package (no clean-tree claim).
finalize     turns a windows-package.ps1 / linux-package.sh package into an
             SDK: bundled vendored static libraries, link order from the
             example_workbench dependency graph, system libraries from its
             mcpp link line, manifest.json with toolchain, mcpp version,
             vendored dependency versions and a SHA-256 for every file, a
             CMake config package, the consumer sample and README.md.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tomllib
from pathlib import Path

from sdk_package_cmake import cmake_config, cmake_version_file, readme
from sdk_package_headers import validate_sdk_headers
from sdk_package_provenance import (
    compiler_info, mcpp_info, msvc_runtime, pacman_versions, sha256,
    vendored_dependencies, vulkan_sdk_version)

LINK_ROOT = "examples/workbench"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True,
        text=True).stdout


def status_lines(repo: Path) -> list[str]:
    output = git(repo, "status", "--porcelain", "--untracked-files=all")
    return [line for line in output.splitlines() if line.strip()]


def check_clean(repo: Path, allow_untracked: bool) -> None:
    problems = []
    for line in status_lines(repo):
        path = line[3:].strip('"')
        if line.startswith("??"):
            if not allow_untracked:
                problems.append(f"untracked: {path}")
        else:
            problems.append(f"changed: {path}")
    if problems:
        raise SystemExit(
            f"refusing to package {repo}: the tree is not clean\n  "
            + "\n  ".join(problems))


def write_workspace(repo: Path, output: Path, cxx_runtime: str) -> None:
    """A workspace in `output` over the repository's library and example
    members (not tests or tools), with `cxx_runtime` for the whole graph."""
    text = (repo / "mcpp.toml").read_text("utf-8")
    members = tomllib.loads(text)["workspace"]["members"]
    relative = Path(os.path.relpath(repo, output)).as_posix()
    chosen = [m for m in members if not m.startswith("tests/")]
    listing = "".join(f'    "{relative}/{m}",\n' for m in chosen)
    text = re.sub(r"members = \[\n.*?\n\]", "members = [\n" + listing + "]",
                  text, count=1, flags=re.S)
    # mcpp resolves tool paths relative to this generated manifest, not the
    # source workspace. Keep the Xcode archiver and Linux GCC prefix reachable.
    text = text.replace('ar = "scripts/dev/macos-ar.py"',
                        f'ar = "{relative}/scripts/dev/macos-ar.py"')
    text = text.replace('path = "tools/linux-gcc"',
                        f'path = "{relative}/tools/linux-gcc"')
    text, count = re.subn(r'cxx_runtime = "[a-z-]+"',
                          f'cxx_runtime = "{cxx_runtime}"', text)
    if count != 1:
        raise SystemExit("mcpp.toml: expected one [workspace.build] cxx_runtime")
    header = ("# Generated by scripts/ci/sdk-package.py workspace from the "
              "repository's mcpp.toml; do not edit.\n")
    write_text(output / "mcpp.toml", header + text)
    print(output / "mcpp.toml")


def cfg_matches(selector: str, platform: str) -> bool:
    """Evaluates the cfg(...) selectors the manifests use, for an OS."""
    expression = selector.strip()
    match = re.fullmatch(r"cfg\((.*)\)", expression)
    if match:
        expression = match.group(1)

    def evaluate(text: str) -> bool:
        text = text.strip()
        inner = re.fullmatch(r"(not|any|all)\((.*)\)", text)
        if inner:
            parts = [p for p in re.split(r",\s*(?![^()]*\))", inner.group(2)) if p.strip()]
            values = [evaluate(part) for part in parts]
            return {"not": lambda: not values[0], "any": lambda: any(values),
                    "all": lambda: all(values)}[inner.group(1)]()
        os_match = re.fullmatch(r'os\s*=\s*"([a-z]+)"', text)
        if not os_match:
            raise SystemExit(f"unsupported cfg selector: {selector}")
        return os_match.group(1) == platform

    return evaluate(expression)


def package_dependencies(package: Path, platform: str) -> list[Path]:
    manifest = tomllib.loads((package / "mcpp.toml").read_text("utf-8"))
    tables = [manifest.get("dependencies", {})]
    for selector, table in manifest.get("target", {}).items():
        if cfg_matches(selector, platform):
            tables.append(table.get("dependencies", {}))
    result = []
    for table in tables:
        for namespace in table.values():
            for entry in namespace.values():
                result.append((package / entry["path"]).resolve())
    return result


def link_order(repo: Path, platform: str) -> list[dict]:
    """The libraries of example_workbench's dependency graph, each before
    the libraries it depends on (reverse post-order of a depth-first walk
    in manifest order): the order a single-pass linker needs."""
    order: list[Path] = []
    seen: set[Path] = set()

    def visit(package: Path) -> None:
        if package in seen:
            return
        seen.add(package)
        for dependency in package_dependencies(package, platform):
            visit(dependency)
        order.append(package)

    visit((repo / LINK_ROOT).resolve())
    libraries = []
    for package in reversed(order[:-1]):
        manifest = tomllib.loads((package / "mcpp.toml").read_text("utf-8"))
        targets = [name for name, target in manifest.get("targets", {}).items()
                   if target.get("kind") == "lib"]
        if len(targets) != 1:
            raise SystemExit(f"{package}: expected one lib target, found {targets}")
        info = manifest["package"]
        vendored = package.parent.name == "third_party"
        libraries.append({
            "name": targets[0], "package": info["name"],
            "origin": f"vendored {info['name']} {info['version']}" if vendored else "cgpui",
        })
    return libraries


def link_edge(build_dir: Path, program: str) -> list[str]:
    """The ldflags words of a program's link edge in mcpp's build.ninja."""
    lines = (build_dir / "build.ninja").read_text("utf-8").splitlines()
    pattern = re.compile(rf"^build \S*/{re.escape(program)}(\.exe)? :")
    for index, line in enumerate(lines):
        if pattern.match(line):
            for following in lines[index + 1:index + 12]:
                stripped = following.strip()
                if stripped.startswith("ldflags ="):
                    return re.findall(r'"[^"]*"|\S+', stripped[len("ldflags ="):])
                if following.startswith("build "):
                    break
            return []
    raise SystemExit(f"no {program} link edge in {build_dir / 'build.ninja'}")


def system_libraries(words: list[str], platform: str, own: set[str]) -> tuple[list[str], list[str]]:
    names, dirs = [], []
    for word in words:
        word = word.strip('"')
        if platform == "windows":
            if word.upper().startswith("/LIBPATH:"):
                dirs.append(word[len("/LIBPATH:"):])
            elif word.lower().endswith(".lib"):
                names.append(word[:-4])
        elif word.startswith("-L"):
            dirs.append(word[2:])
        elif word.startswith("-l"):
            names.append(word[2:])
    ordered = [name for name in dict.fromkeys(names) if name not in own]
    return ordered, dirs












def file_entries(package_root: Path) -> list[dict]:
    files = sorted(
        (path.relative_to(package_root).as_posix(), path)
        for path in package_root.rglob("*")
        if path.is_file() and path.name not in (
            "manifest.json", "release-manifest.json"))
    return [{"path": relative, "size": path.stat().st_size,
             "sha256": sha256(path)} for relative, path in files]


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def project_version(repo: Path) -> str:
    manifest = tomllib.loads((repo / "packages/core/mcpp.toml").read_text("utf-8"))
    return manifest["package"]["version"]





def library_file(build_dir: Path, library: dict, platform: str) -> Path:
    name = f"{library['name']}.lib" if platform == "windows" else f"lib{library['name']}.a"
    path = build_dir / "bin" / library["package"] / name
    if not path.is_file():
        raise SystemExit(f"missing library: {path}")
    return path


def copy_libraries(args, libraries: list[dict], package_root: Path) -> None:
    lib_root = package_root / "lib"
    lib_root.mkdir(parents=True, exist_ok=True)
    for library in libraries:
        source = library_file(args.build_dir, library, args.platform)
        destination = lib_root / source.name
        shutil.copyfile(source, destination)
        library["path"] = f"lib/{destination.name}"
        if args.platform == "windows":
            library["msvc_runtime"] = msvc_runtime(args.build_dir, destination)
            if library["msvc_runtime"] != args.runtime:
                raise SystemExit(
                    f"{destination.name} uses /{library['msvc_runtime']}, "
                    f"expected /{args.runtime}")
    linked = {Path(library["path"]).name for library in libraries}
    extra = [path.name for path in lib_root.iterdir()
             if path.is_file() and path.name not in linked]
    if extra:
        raise SystemExit(f"libraries missing from the link order: {extra}")


def copy_programs(args, package_root: Path) -> list[str]:
    """Programs named <package>/<target>: bin/<package>/<target>[.exe]."""
    suffix = ".exe" if args.platform == "windows" else ""
    executables = []
    (package_root / "bin").mkdir(parents=True, exist_ok=True)
    for name in args.executable:
        package, target = name.split("/")
        source = args.build_dir / "bin" / package / f"{target}{suffix}"
        if not source.is_file():
            raise SystemExit(f"missing executable: {source}")
        shutil.copy2(source, package_root / "bin" / source.name)
        executables.append(f"bin/{source.name}")
    sample = package_root / "share" / "cgpui" / "sdk_consumer"
    if sample.exists():
        shutil.rmtree(sample)
    shutil.copytree(args.repo_root / "examples" / "sdk_consumer", sample)
    return executables


def write_cmake(package_root: Path, version: str, platform: str, mode: str,
                runtime: str | None, libraries: list[dict], system: list[str]) -> None:
    cmake_root = package_root / "lib" / "cmake" / "cgpui"
    write_text(cmake_root / "cgpuiConfig.cmake",
               cmake_config(platform, mode, runtime, libraries, system))
    write_text(cmake_root / "cgpuiConfigVersion.cmake", cmake_version_file(version))


def stage_macos(args) -> None:
    repo, root = args.repo_root.resolve(), args.package_root
    validate_sdk_headers(root)
    libraries = link_order(repo, "macos")
    copy_libraries(args, libraries, root)
    for lib in libraries:
        if sha256(root / lib["path"]) != sha256(library_file(args.build_dir, lib, "macos")):
            raise SystemExit(f"staged library differs from build output: {lib['path']}")
    words = link_edge(args.build_dir, "example_workbench")
    system, _ = system_libraries(words, "macos", {lib["name"] for lib in libraries})
    frameworks = list(dict.fromkeys(name.strip('"') for flag, name in zip(words, words[1:])
                                    if flag == "-framework"))
    version = project_version(repo)
    write_cmake(root, version, "macos", args.mode, None, libraries,
                system + [f"-framework {name}" for name in frameworks])
    manifest = {
        "schema_version": 2, "package": f"cgpui-macos-{args.arch}-{args.mode}",
        "platform": "macos", "architecture": args.arch, "mode": args.mode,
        "deployment_target": "26.0", "version": version, "cxx_standard": "c++23",
        "header_root": "include/cgpui",
        "libraries": [lib["path"] for lib in libraries],
        "link_names": [lib["name"] for lib in libraries],
        "system_libraries": system, "frameworks": frameworks,
        "cmake_config": "lib/cmake/cgpui/cgpuiConfig.cmake",
        "executables": copy_programs(args, root), "consumer_sample": "share/cgpui/sdk_consumer",
        "documents": ["README.md"],
        "metadata": ["metadata/build.json", "metadata/mcpp.toml", "metadata/VENDORED.md"],
    }
    for license_path in ("lunasvg/LICENSE", "plutovg/LICENSE", "plutovg/source/FTL.TXT"):
        relative = f"metadata/licenses/{license_path}"
        (root / relative).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(repo / "third_party" / license_path, root / relative)
        manifest["metadata"].append(relative)
    write_text(root / "manifest.json", json.dumps(manifest, indent=2) + "\n")


def finalize(args) -> None:
    repo, package_root = args.repo_root, args.package_root
    check_clean(repo, allow_untracked=False)
    validate_sdk_headers(package_root)
    libraries = link_order(repo, args.platform)
    copy_libraries(args, libraries, package_root)
    own = {library["name"] for library in libraries}
    system, dirs = system_libraries(
        link_edge(args.build_dir, "example_workbench"), args.platform, own)
    executables = copy_programs(args, package_root)
    architecture = "x64" if args.platform == "windows" else "x86_64"
    name = f"cgpui-sdk-{args.platform}-{architecture}-{args.mode}"
    bundled = {library["package"] for library in libraries
               if library["origin"] != "cgpui"}
    manifest = {
        "schema_version": 4,
        "package": name,
        "version": project_version(repo),
        "git_commit": git(repo, "rev-parse", "HEAD").strip(),
        "dirty": False,
        "source_check": "git status --porcelain empty before the build "
                        "and after it",
        "platform": args.platform,
        "architecture": architecture,
        "mode": args.mode,
        "cxx_standard": "c++23",
        "build_system": dict(mcpp_info(args.mcpp, args.workspace),
                             profile=args.profile),
        "compiler": compiler_info(args.build_dir, args.platform),
        "header_root": "include/cgpui",
        "libraries": [library["path"] for library in libraries],
        "link_names": [library["name"] for library in libraries],
        "library_origins": {library["name"]: library["origin"]
                            for library in libraries},
        "system_libraries": system,
        "vendored_dependencies": vendored_dependencies(repo, bundled),
        "link_order_source": "example_workbench dependency graph "
                             "(examples/workbench/mcpp.toml); system "
                             "libraries from its mcpp link line",
        "executables": executables,
        "cmake_config": "lib/cmake/cgpui/cgpuiConfig.cmake",
        "consumer_sample": "share/cgpui/sdk_consumer",
        "shaders": "embedded as SPIR-V in cgpui_renderer_vulkan",
        "documents": ["README.md"],
    }
    if args.platform == "windows":
        manifest["msvc_runtime"] = args.runtime
        manifest["vulkan_sdk_version"] = vulkan_sdk_version(dirs)
    else:
        manifest["system_packages"] = pacman_versions()
    write_text(package_root / "README.md", readme(manifest))
    write_cmake(package_root, manifest["version"], args.platform, args.mode,
                args.runtime, libraries, system)
    manifest["files"] = file_entries(package_root)
    write_text(package_root / "manifest.json",
               json.dumps(manifest, indent=2) + "\n")
    check_clean(repo, allow_untracked=False)
    print(json.dumps({"package": name, "files": len(manifest["files"])}))


def main() -> int:
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)
    clean = commands.add_parser("check-clean")
    clean.add_argument("--repo-root", type=Path, required=True)
    clean.add_argument("--allow-untracked", action="store_true")
    workspace = commands.add_parser("workspace")
    workspace.add_argument("--repo-root", type=Path, required=True)
    workspace.add_argument("--output", type=Path, required=True)
    workspace.add_argument("--cxx-runtime", required=True,
                           choices=("self-contained", "toolchain-coupled", "host-coupled"))
    mac = commands.add_parser("stage-macos")
    mac.set_defaults(platform="macos", executable=["hello-window/hello_window"])
    mac.add_argument("--arch", choices=("arm64",), required=True)
    mac.add_argument("--mode", choices=("debug", "release"), required=True)
    mac.add_argument("--repo-root", type=Path, required=True)
    mac.add_argument("--build-dir", type=Path, required=True)
    mac.add_argument("--package-root", type=Path, required=True)
    final = commands.add_parser("finalize")
    final.add_argument("--platform", choices=("windows", "linux"), required=True)
    final.add_argument("--mode", choices=("debug", "release"), required=True)
    final.add_argument("--profile", required=True)
    final.add_argument("--runtime", choices=("MD", "MT"))
    final.add_argument("--repo-root", type=Path, required=True)
    final.add_argument("--workspace", type=Path, required=True)
    final.add_argument("--build-dir", type=Path, required=True)
    final.add_argument("--mcpp", required=True)
    final.add_argument("--package-root", type=Path, required=True)
    final.add_argument("--executable", action="append", default=[])
    args = parser.parse_args()
    if args.command == "check-clean":
        check_clean(args.repo_root, args.allow_untracked)
        print(git(args.repo_root, "rev-parse", "HEAD").strip())
        return 0
    if args.command == "workspace":
        write_workspace(args.repo_root.resolve(), args.output.resolve(), args.cxx_runtime)
        return 0
    if args.command == "stage-macos":
        stage_macos(args)
        return 0
    if args.platform == "windows" and args.runtime is None:
        parser.error("--runtime is required on Windows")
    finalize(args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
